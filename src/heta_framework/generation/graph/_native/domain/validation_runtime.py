"""Runtime validation as two reusable phases, with an artifact-level cache.

The validation chain (static → data materialization → Harbor oracle/nop) used to live entirely
in ``poc.run_validation``, driven by a Python loop *after* the dataset had been generated. This
module holds the mechanics with no Data Designer dependency, so the same code serves both:

* ``dd/validation.py`` — the columns that run the phases inside a Data Designer workflow, where
  the scheduler owns ordering, concurrency and row-group checkpointing;
* ``poc.run_validation`` — a thin wrapper for callers that just want the verdict for one package.

**Why a cache lives here.** Data Designer caches whole *stages* by config fingerprint, which
cannot see what is inside a generated package. Validation costs minutes of Docker/Harbor per
package and its verdict depends on package content, Harbor version and the requested repeats, so
the expensive phases keep their own content-addressed record next to the package
(``authoring/validation/validation_cache.json``). A row that already has a verdict for the exact
same inputs is answered from that record; ``OD_REVALIDATE=1`` (or ``force=True``) ignores it.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path
from typing import Any

from heta_framework.generation.graph._native.domain import harbor as harbor_module
from heta_framework.generation.graph._native.domain.runtime_materialize import docker_available, materialize_package
from heta_framework.generation.graph._native.io_utils import atomic_write_json, canonical_json_sha256, read_json, tree_hashes

CACHE_SCHEMA_VERSION = "omegadesigner.validation_cache.v1"
REPORT_SCHEMA_VERSION = "omegadesigner.package_validation.v1"
#: Paths inside a package that hold *validation output*, not the package under test.
#: `environment/data` and `tests/data` are generated by the materialization phase itself, so
#: including them would change the key between phase 1 and phase 2 (observed: the phase-2 write
#: reset the cache and discarded the materialization verdict). They are a deterministic function
#: of the authored generator, which *is* hashed.
_NON_CONTENT_PREFIXES = ("authoring/", "environment/data/", "tests/data/")


def revalidate_requested() -> bool:
    """``OD_REVALIDATE=1`` ignores cached verdicts (both inside and outside a Data Designer run)."""
    import os

    return str(os.environ.get("OD_REVALIDATE", "")).strip().lower() in {"1", "true", "yes", "on"}


def package_content_sha256(package_dir: str | Path) -> str:
    """Identity of the package *under test*: every file except the validation's own output.

    Using the manifest's ``files_sha256`` would only cover the rendered file map; hashing the
    tree on disk also catches a package that was edited (or partially materialized) after
    generation, which is exactly the case a cache must not hide.
    """
    package = Path(package_dir)
    content = {
        relative: digest
        for relative, digest in tree_hashes(package).items()
        if not any(relative.startswith(prefix) for prefix in _NON_CONTENT_PREFIXES)
    }
    return canonical_json_sha256(content)


def validation_key(
    package_dir: str | Path,
    *,
    oracle_repeats: int,
    harbor_env: str = "docker",
) -> dict[str, Any]:
    """Everything that can change the verdict; a cache entry is only reused for an equal key."""
    return {
        "package_sha256": package_content_sha256(package_dir),
        "oracle_repeats": int(oracle_repeats),
        "harbor_env": harbor_env,
        "harbor_version": harbor_module.harbor_version(),
        "docker_available": docker_available(),
    }


def cache_path(package_dir: str | Path) -> Path:
    return Path(package_dir) / "authoring" / "validation" / "validation_cache.json"


def read_cache(package_dir: str | Path) -> dict[str, Any]:
    path = cache_path(package_dir)
    if not path.is_file():
        return {}
    try:
        cache = read_json(path)
    except (OSError, ValueError):
        return {}
    return cache if isinstance(cache, dict) else {}


def _write_cache(package_dir: str | Path, cache: dict[str, Any]) -> None:
    """Merge-and-write: a phase only replaces its own section, so the other one survives."""
    path = cache_path(package_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    current = read_cache(package_dir)
    if current.get("key") != cache.get("key"):
        current = {"schema_version": CACHE_SCHEMA_VERSION, "key": cache.get("key")}
    current.update(cache)
    current["schema_version"] = CACHE_SCHEMA_VERSION
    atomic_write_json(path, current)


def _materialize_payload(result: Any) -> dict[str, Any]:
    return {
        "ok": bool(result.ok),
        "built": bool(result.built),
        "deterministic": result.deterministic,
        "generation_runs": int(result.generation_runs),
        "image": result.image,
        "hardening_deviations": list(result.hardening.deviations),
        "materialized_paths": list(result.materialized),
        "errors": list(result.errors),
        "warnings": list(result.warnings),
        "docker_available": bool(result.docker_available),
    }


def _harbor_payload(validation: dict[str, Any]) -> dict[str, Any]:
    oracle = validation.get("oracle") or {}
    nop = validation.get("nop") or {}
    return {
        "passed": bool(validation.get("passed")),
        "oracle_rewards": [run.get("reward") for run in oracle.get("runs", [])],
        "nop_reward": (nop.get("runs") or [{}])[0].get("reward"),
        "oracle_passed": bool(oracle.get("passed")),
        "nop_passed": bool(nop.get("passed")),
        "errors": list(validation.get("errors") or []),
        "detail": validation,
    }


def materialization_phase(
    package_dir: str | Path,
    *,
    oracle_repeats: int = 2,
    harbor_env: str = "docker",
    timeout_floor_sec: int = 300,
    cancelled: Callable[[], bool] | None = None,
    force: bool = False,
) -> dict[str, Any]:
    """Phase 1: build the generator image, run it twice, verify reproducibility.

    Returns the column payload. Never raises: a broken Docker daemon, a failing build or a
    cancelled run all come back as ``ok=False`` plus ``errors``.
    """
    package = Path(package_dir)
    key = validation_key(package, oracle_repeats=oracle_repeats, harbor_env=harbor_env)
    if not force:
        cached = read_cache(package)
        if cached.get("key") == key and cached.get("materialize"):
            return {"cache_hit": True, **cached["materialize"]}
    try:
        result = materialize_package(package, timeout_floor_sec=timeout_floor_sec, cancelled=cancelled)
        payload = _materialize_payload(result)
    except Exception as error:  # noqa: BLE001 - a rejected package is a value, not an exception
        payload = {
            "ok": False,
            "built": False,
            "deterministic": None,
            "generation_runs": 0,
            "image": "",
            "hardening_deviations": [],
            "materialized_paths": [],
            "errors": [f"materialization raised: {type(error).__name__}: {error}"],
            "warnings": [],
            "docker_available": docker_available(),
        }
    # A new key means any earlier Harbor verdict was for different content: drop it.
    _write_cache(package, {"key": key, "materialize": payload, "harbor": None})
    return {"cache_hit": False, **payload}


def harbor_phase(
    package_dir: str | Path,
    *,
    oracle_repeats: int = 2,
    harbor_env: str = "docker",
    cancelled: Callable[[], bool] | None = None,
    force: bool = False,
) -> dict[str, Any]:
    """Phase 2: Harbor oracle × repeats and nop × 1, judged fail-closed. Never raises."""
    package = Path(package_dir)
    key = validation_key(package, oracle_repeats=oracle_repeats, harbor_env=harbor_env)
    if not force:
        cached = read_cache(package)
        if cached.get("key") == key and cached.get("harbor"):
            return {"cache_hit": True, **cached["harbor"]}
    validation = harbor_module.validate_package_harbor(
        package, harbor_env=harbor_env, oracle_repeats=oracle_repeats, cancelled=cancelled
    )
    payload = _harbor_payload(validation)
    _write_cache(package, {"key": key, "harbor": payload})
    return {"cache_hit": False, **payload}


def cached_harbor_detail(package_dir: str | Path) -> dict | None:
    """Full Harbor evidence (per-trial rewards, returncodes, log paths) from the cache.

    The dataset row only carries the verdict and the rewards; the report that travels with the
    package must still contain the trial-level detail the standalone path used to embed, so the
    verdict column reads it back from the cache instead of carrying it through the dataset.
    """
    cached = read_cache(package_dir)
    detail = ((cached.get("harbor") or {}) if isinstance(cached.get("harbor"), dict) else {}).get("detail")
    return detail if isinstance(detail, dict) else None


def build_report(
    package_dir: str | Path,
    *,
    static: dict[str, Any] | None,
    materialize: dict[str, Any] | None,
    harbor: dict[str, Any] | None,
    settings_domain: str = "",
    settings_field: str = "",
) -> dict[str, Any]:
    """Assemble the report shape Omega persists next to the package (validated in tests)."""
    report: dict[str, Any] = {
        "package": str(Path(package_dir).resolve()),
        "static_passed": bool((static or {}).get("passed")),
        "data_materialized": bool((materialize or {}).get("ok")),
        "deterministic": (materialize or {}).get("deterministic"),
        # The verdict is the AND of the three gates, recomputed here rather than trusting the
        # Harbor phase's own flag: a column that ran before its prerequisites (or a caller that
        # hand-built the payloads) must never be able to report `ready` on a partial chain.
        "terminal_bench_ready": bool(
            (static or {}).get("passed") and (materialize or {}).get("ok") and (harbor or {}).get("passed")
        ),
        "errors": [],
        "hardening_deviations": list((materialize or {}).get("hardening_deviations") or []),
        "materialize_errors": list((materialize or {}).get("errors") or []),
        "materialized_paths": list((materialize or {}).get("materialized_paths") or []),
    }
    if static is not None:
        report["static"] = {
            "passed": bool(static.get("passed")),
            "failed": list(static.get("failed") or []),
            "attempted": static.get("attempted"),
        }
        if not report["static_passed"]:
            report["errors"].append("static contract checks failed")
    if materialize is not None and not report["data_materialized"]:
        report["errors"].extend(report["materialize_errors"] or ["data materialization failed"])
    report["harbor"] = (harbor or {}).get("detail") if harbor else None
    if harbor is not None:
        if not (harbor or {}).get("passed"):
            report["errors"].append("harbor oracle/nop gate failed")
    else:
        report["terminal_bench_ready"] = False
        report["errors"].append("harbor gate not requested; cannot be terminal_bench_ready")
    for phase, name in ((materialize, "materialize"), (harbor, "harbor")):
        if phase and phase.get("cache_hit"):
            report.setdefault("cache_hits", []).append(name)
    report["settings_domain"] = settings_domain
    report["settings_field"] = settings_field
    report["schema_version"] = REPORT_SCHEMA_VERSION
    return report


def write_report(package_dir: str | Path, report: dict[str, Any]) -> Path:
    """Persist the report next to the package and promote the manifest status."""
    package = Path(package_dir)
    validation_dir = package / "authoring" / "validation"
    validation_dir.mkdir(parents=True, exist_ok=True)
    path = validation_dir / "validation_report.json"
    atomic_write_json(path, report)

    manifest_path = package / "generation_manifest.json"
    if manifest_path.is_file():
        manifest = read_json(manifest_path)
        manifest["status"] = "terminal_bench_ready" if report["terminal_bench_ready"] else manifest.get("status")
        manifest["validation"] = {
            "output_mode": "omegadesigner",
            "mat_deterministic": bool(report.get("deterministic")),
            "scientific_contract_passed": bool(report.get("static_passed")),
            "code_implemented": bool(report.get("data_materialized")),
            "tests_passed": bool(report.get("terminal_bench_ready")),
            "terminal_bench_ready": bool(report["terminal_bench_ready"]),
        }
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path


def validation_summary(report: dict[str, Any]) -> dict[str, Any]:
    """Small verdict value for the dataset column (paths and counts, not the full logs)."""
    harbor = report.get("harbor") or {}
    oracle_runs = ((harbor.get("oracle") or {}).get("runs")) or []
    nop_runs = ((harbor.get("nop") or {}).get("runs")) or []
    return {
        "static_passed": bool(report.get("static_passed")),
        "data_materialized": bool(report.get("data_materialized")),
        "deterministic": report.get("deterministic"),
        "terminal_bench_ready": bool(report.get("terminal_bench_ready")),
        "errors": list(report.get("errors") or [])[:5],
        "hardening_deviations": list(report.get("hardening_deviations") or []),
        "oracle_rewards": [run.get("reward") for run in oracle_runs],
        "nop_reward": nop_runs[0].get("reward") if nop_runs else None,
    }


